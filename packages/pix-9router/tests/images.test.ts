import { describe, expect, it } from "bun:test";
import type { ImageModel, ImagesContext, ImagesOptions } from "@xynogen/pix-data/ai";
import { generateImages } from "../src/images.ts";
import { providerConfig, toImageModelConfig } from "../src/provider.ts";

const model: ImageModel<"9router-images"> = {
	type: "image",
	id: "gemini/gemini-3-pro-image-preview",
	name: "Gemini Image",
	api: "9router-images",
	provider: "9router",
	baseUrl: "https://router.test/v1",
	input: ["text"],
	output: ["image"],
	cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
};
const context: ImagesContext = { input: [{ type: "text", text: "blue sky" }] };
const png = "iVBORw0KGgo=";

describe("9Router images", () => {
	it("registers an image model separately from chat", () => {
		expect(toImageModelConfig({ id: model.id, name: model.name })).toMatchObject({
			type: "image",
			api: "9router-images",
			id: model.id,
			input: ["text"],
			output: ["image"],
		});
		const config = providerConfig("key", model.baseUrl, [{ id: "chat-model" }], [{ id: model.id }]);
		expect(config.models).toHaveLength(2);
		expect(config.models[0]?.type).toBeUndefined();
		expect(config.models[1]?.type).toBe("image");
		expect(config.images["9router-images"].generateImages).toBe(generateImages);
	});

	it("serves cached image models offline and fetches both lists on explicit refresh", async () => {
		const config = providerConfig("key", model.baseUrl, [{ id: "chat-model" }], [{ id: model.id }]);
		const original = globalThis.fetch;
		const urls: string[] = [];
		try {
			globalThis.fetch = Object.assign(
				async (url: string | URL | Request) => {
					urls.push(String(url));
					return Response.json({
						data: [{ id: String(url).endsWith("/image") ? "fresh-image" : "fresh-chat" }],
					});
				},
				{ preconnect: fetch.preconnect },
			);
			const refresh = { publish: async () => true, signal: new AbortController().signal };
			const offline = await config.refreshModels({ ...refresh, allowNetwork: false });
			expect(offline?.map((entry) => entry.id)).toEqual(["chat-model", model.id]);
			expect(urls).toEqual([]);
			const refreshed = await config.refreshModels({ ...refresh, allowNetwork: true });
			expect(refreshed?.map((entry) => entry.id)).toEqual(["fresh-chat", "fresh-image"]);
			expect(refreshed?.[1]?.type).toBe("image");
			expect(urls).toEqual([`${model.baseUrl}/models`, `${model.baseUrl}/models/image`]);
		} finally {
			globalThis.fetch = original;
		}
	});

	it("keeps cached image models when image discovery is unavailable", async () => {
		const config = providerConfig("key", model.baseUrl, [], [{ id: model.id }]);
		const original = globalThis.fetch;
		try {
			globalThis.fetch = Object.assign(
				async (url: string | URL | Request) =>
					String(url).endsWith("/image")
						? new Response(null, { status: 404 })
						: Response.json({ data: [{ id: "fresh-chat" }] }),
				{ preconnect: fetch.preconnect },
			);
			const result = await config.refreshModels({
				allowNetwork: true,
				publish: async () => true,
				signal: new AbortController().signal,
			});
			expect(result?.map((entry) => entry.id)).toEqual(["fresh-chat", model.id]);
		} finally {
			globalThis.fetch = original;
		}
	});

	it("posts to images/generations and returns generated bytes", async () => {
		const requests: { url: string; init: RequestInit }[] = [];
		const responses: number[] = [];
		const options: ImagesOptions = {
			apiKey: "test-key",
			fetch: Object.assign(
				async (url: string | URL | Request, init?: RequestInit) => {
					requests.push({ url: String(url), init: init ?? {} });
					return Response.json({ data: [{ b64_json: png }] });
				},
				{ preconnect: fetch.preconnect },
			),
			onResponse: (response) => {
				responses.push(response.status);
			},
		};
		const result = await generateImages(model, context, options);
		expect(result.stopReason).toBe("stop");
		expect(result.output).toEqual([{ type: "image", data: png, mimeType: "image/png" }]);
		expect(requests[0]?.url).toBe("https://router.test/v1/images/generations");
		expect(new Headers(requests[0]?.init.headers).get("Authorization")).toBe("Bearer test-key");
		expect(JSON.parse(String(requests[0]?.init.body))).toEqual({
			model: model.id,
			prompt: "blue sky",
			response_format: "b64_json",
		});
		expect(responses).toEqual([200]);
	});

	it("rejects reference images before calling the endpoint", async () => {
		const result = await generateImages(
			model,
			{ input: [{ type: "image", data: "aGVsbG8=", mimeType: "image/png" }] },
			{
				apiKey: "test-key",
				fetch: Object.assign(
					() => {
						throw new Error("must not call fetch");
					},
					{ preconnect: fetch.preconnect },
				),
			},
		);
		expect(result.stopReason).toBe("error");
		expect(result.errorMessage).toContain("reference images");
	});

	it("reports a failed or empty response, not an empty success", async () => {
		for (const response of [new Response("down", { status: 503 }), Response.json({ data: [] })]) {
			const result = await generateImages(model, context, {
				apiKey: "test-key",
				fetch: Object.assign(async () => response, { preconnect: fetch.preconnect }),
			});
			expect(result.stopReason).toBe("error");
			expect(result.errorMessage).toBeTruthy();
		}
	});

	it("detects JPEG output and rejects invalid image data", async () => {
		for (const [data, mimeType] of [
			["/9j/AA==", "image/jpeg"],
			["aGVsbG8=", undefined],
		] as const) {
			const result = await generateImages(model, context, {
				apiKey: "test-key",
				fetch: Object.assign(async () => Response.json({ data: [{ b64_json: data }] }), {
					preconnect: fetch.preconnect,
				}),
			});
			expect(result.stopReason).toBe(mimeType ? "stop" : "error");
			if (mimeType) expect(result.output[0]).toEqual({ type: "image", data, mimeType });
		}
	});
});
